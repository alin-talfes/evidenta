import fs from 'node:fs';
import assert from 'node:assert/strict';
const html = fs.readFileSync('index.html', 'utf8');
const exp = fs.readFileSync('js/export.js', 'utf8');
const app = fs.readFileSync('js/app.js', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');
assert.ok(html.includes('id="exportPvIncarcerareBtn"'), 'PV button missing');
assert.ok(html.includes('onclick="exportPvIncarcerarePDF()"'), 'PV handler missing');
assert.ok(exp.includes('function buildPvIncarcerareHTML()'), 'PV builder missing');
assert.ok(exp.includes('function exportPvIncarcerarePDF()'), 'PV exporter missing');
assert.ok(exp.includes('PROCES-VERBAL DE CONFIRMARE'), 'PV title missing');
assert.ok(exp.includes('const arrestText=deductionRows.length?deductionRows.map') && exp.includes('${arrestText}'), 'PV trebuie să prezinte distinct toate perioadele deduse, cu intervalele și zilele aferente');
assert.ok(exp.includes('const recursText=manualRows.length?manualRows.map') && exp.includes('pvEsc(recursText)'), 'PV trebuie să defalce separat fiecare tranșă de recurs compensatoriu');
assert.ok(exp.includes('const nonText=(c.nonRowsData||[])') && exp.includes('+nonText+'), 'PV trebuie să defalce perioadele adăugate și numărul de zile aferent');
assert.ok(exp.includes('Instanța emitentă a mandatului de executare'), 'PV trebuie să păstreze adresarea către instanța emitentă');
assert.ok(!exp.includes('expirarea teoretică') && !exp.includes('expirării teoretice'), 'PV și nota internă nu trebuie să menționeze expirarea teoretică');
assert.ok(exp.includes('expiry=pvDate(c.realExp)'), 'Data expirării din PV trebuie să provină din expirarea reală, fără fallback teoretic');
assert.ok(exp.includes('art. 557 alin. (7) și (8)'), 'legal reference missing');
assert.ok(exp.includes('ȘEF STRUCTURĂ EVIDENȚĂ DEȚINUȚI') && exp.includes('DIRECTOR'), 'signature fields missing');
assert.ok(exp.includes('function buildNotaInternaHTML()'), 'internal note builder missing');
assert.ok(exp.includes('Către Compartimentul Organizarea Muncii'), 'internal note addressee missing');
assert.ok(exp.includes('AM PRIMIT') && exp.includes('AM PREDAT'), 'receipt/hand-over fields missing');
assert.ok(exp.includes('grid-template-columns:39% 61%'), 'two-column internal note layout missing');
assert.ok(app.includes('dedRowsData: (window.ManualDeductionRules?.collectRows?.() || [])'), 'typed deduction data missing');
assert.ok(sw.includes("const VERSION = 'v103'"), 'service-worker cache version missing');
console.log('PV incarceration export checks passed');
